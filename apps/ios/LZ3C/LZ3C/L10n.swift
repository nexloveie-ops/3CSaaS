import SwiftUI

enum AppLang: String, CaseIterable, Identifiable {
    case en
    case zh

    var id: String { rawValue }

    var shortLabel: String {
        switch self {
        case .en: return "EN"
        case .zh: return "中文"
        }
    }

    mutating func toggle() {
        self = self == .en ? .zh : .en
    }
}

@MainActor
final class LanguageStore: ObservableObject {
    @Published private(set) var lang: AppLang {
        didSet { UserDefaults.standard.set(lang.rawValue, forKey: Self.storageKey) }
    }

    private static let storageKey = "lz3c.appLang"

    init() {
        if let raw = UserDefaults.standard.string(forKey: Self.storageKey),
           let saved = AppLang(rawValue: raw) {
            lang = saved
        } else {
            lang = .zh
        }
    }

    func set(_ lang: AppLang) {
        guard self.lang != lang else { return }
        self.lang = lang
    }

    func t(_ key: String) -> String {
        let table = lang == .zh ? Self.zh : Self.en
        return table[key] ?? Self.en[key] ?? key
    }

    func tf(_ key: String, _ args: CVarArg...) -> String {
        String(format: t(key), arguments: args)
    }

