struct LanguageToggle: View {
    @EnvironmentObject private var language: LanguageStore

    var body: some View {
        HStack(spacing: 0) {
            chip(.en)
            chip(.zh)
        }
        .padding(2)
        .background(Capsule().fill(Color.white))
        .overlay(Capsule().strokeBorder(ShopTheme.border, lineWidth: 1))
    }

    private func chip(_ lang: AppLang) -> some View {
        let on = language.lang == lang
        return Button {
            language.set(lang)
        } label: {
            Text(lang.shortLabel)
                .font(.system(size: 12, weight: .semibold))
                .foregroundStyle(on ? Color.white : ShopTheme.slate)
                .padding(.horizontal, 10)
                .frame(height: 32)
                .background(Capsule().fill(on ? ShopTheme.indigo : Color.clear))
        }
        .buttonStyle(.plain)
    }
}
